const CURRICULA: Curriculum[] = [CPP];

/** The structured curriculum for a module, if one is authored. */
export function getCurriculum(moduleId?: string | null): Curriculum | null {
  return moduleId ? CURRICULA.find((c) => c.module === moduleId) ?? null : null;
}

/** How many lessons a curriculum holds — for the "N lessons" line on a card. */
export function curriculumLessonCount(c: Curriculum): number {
  return c.chapters.reduce((n, ch) => n + ch.lessons.length, 0);
}

/**
 * The whole curriculum as a roadmap tree, built locally — no generation call.
 *
 * Every lesson is emitted as a `point` with `children: []`. Both parts matter:
 * "point" is what renders a "Start lesson" button, and a non-null `children` is what
 * tells the expander there is nothing here to generate. A generated course fills its
 * leaves in on demand; this one already has them.
 *
 * The tree is identical at every level — a language's order does not change because
 * the learner is experienced. Level still reaches the lessons themselves, through
 * difficultyGuidance() in the lesson agent, which is where "experienced" should show
 * up: denser lessons on the same syllabus, not a different syllabus.
 */
export function curriculumRoadmap(c: Curriculum, level?: string, goal?: string): Roadmap {
  const topics: RoadmapNode[] = c.chapters.map((chapter, i) => ({
    id: `t${i}`,
    kind: "topic",
    title: chapter.title,
    summary: chapter.summary,
    module: c.module,
    children: chapter.lessons.map((lesson, j) => ({
      id: `t${i}-p${j}`,
      kind: "point" as const,
      title: lessonTitle(lesson),
      // Empty for a title-only lesson, which is what every entry still is until its
      // scope line is written. The lesson agent already handles an absent summary —
      // it just generates against the title alone, exactly as before.
      summary: lessonSummary(lesson),
      module: c.module,
      children: [],
    })),
  }));

  return {
    skill: c.title,
    title: c.title,
    summary: c.summary,
    level,
    goal: goal || c.goal,
    topics,
  };
}
