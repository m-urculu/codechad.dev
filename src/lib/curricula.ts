// Structured curricula — pre-authored syllabi for a SINGLE technology.
//
// The third way to start a course, sitting between the two that already exist:
//
//   generated course : the learner picks a technology, answers two questions, and a
//                      grounded model invents the topic list (agents/snowflake.ts).
//   career path      : a fixed, multi-technology curriculum written in paths.ts.
//   curriculum       : THIS — a fixed, single-technology syllabus, deep enough to be
//                      the whole subject rather than one course's worth of it.
//
// WHY a third: a generated roadmap is a dozen topics expanded on demand, which is the
// right shape for "teach me some Rust" and the wrong one for "teach me C++". A language
// has a canonical order — you cannot teach references before objects, or virtual
// dispatch before inheritance — and asking a model to rediscover that order per learner
// produces a different, shallower course every time. So the ORDER is authored here and
// the TEACHING is still generated: every lesson's text, exercise and objectives come
// from the lesson agent, per learner, at their level.
//
// Shape maps onto the roadmap tree the rest of the app already renders:
//
//     curriculum -> Roadmap
//     chapter    -> topic  (t0, t1, …)
//     lesson     -> point  (t0-p0, t0-p1, …)   <- a LEAF: "Start lesson", no expansion
//
// Note the missing level. A generated course and a path both put subtopics between the
// topic and the lesson, because their leaves are invented and something has to hold the
// invention. Here the leaves ARE the syllabus, so a subtopic layer would be a fabricated
// grouping sitting between two authored ones. Chapters carry their lessons directly, and
// `children` is a real array rather than null — which is what stops the expander from
// generating anything, and what makes opening one of these courses cost zero LLM calls
// until the learner actually starts a lesson.

import type { Roadmap, RoadmapNode } from "@/lib/agents/snowflake";

/**
 * One lesson. A bare string is title-only; the object form adds a SCOPE LINE.
 *
 * The scope line is the difference between a syllabus and a list of nouns. "Struct
 * miscellany" tells the lesson agent nothing — it will invent a scope, and two learners
 * asking for the same slot get materially different lessons. Worse, neighbouring
 * lessons ("part 2", "part 3") overlap, because nothing tells either one where its
 * boundary is. So the summary says what this lesson covers AND what it must leave
 * alone because a later lesson owns it.
 *
 * Same idea as PathChapter's optional summary in paths.ts, for the same reason.
 */
export type CurriculumLesson = string | { title: string; summary: string };

export type CurriculumChapter = {
  title: string;
  /** Shown under the chapter in the roadmap, and given to the lesson agent as context. */
  summary: string;
  /** Each becomes one lesson. Ordered; the order is the pedagogy. */
  lessons: CurriculumLesson[];
};

export function lessonTitle(l: CurriculumLesson): string {
  return typeof l === "string" ? l : l.title;
}
export function lessonSummary(l: CurriculumLesson): string {
  return typeof l === "string" ? "" : l.summary;
}

export type Curriculum = {
  /** RUNTIMES id — the module this replaces generation for. */
  module: string;
  title: string;
  summary: string;
  goal: string;
  chapters: CurriculumChapter[];
};

